const { describe, expect, it } = require('@jest/globals');

const pdfDocs = require('../../server/pdf-docs');

describe('pdf-docs', () => {
  it('usa referencias fallback cuando no llegan referencia explicita en packing list e invoice', () => {
    const packing = pdfDocs.generarPackingList({ items: [] });
    const invoice = pdfDocs.generarInvoice({ items: [] });

    expect(packing).toMatch(/Ref: .*PL-/);
    expect(invoice).toMatch(/Invoice: .*INV-/);
  });

  it('escapa pasos de permisos y formatea montos numericos stringificados', () => {
    const resumen = pdfDocs.generarResumenPermisos({
      permisos: [
        {
          icon: '<b>X</b>',
          entidad: 'MTC',
          nombre: 'Homologacion',
          tramite: 'Validacion previa',
          pasos: ['Sube <script>alert(1)</script> y espera respuesta'],
          web: 'https://ejemplo.test',
        },
      ],
    });

    const invoice = pdfDocs.generarInvoice({
      items: [{ desc: 'Telefono', hs: '8517130000', qty: 1, unit: '12,5' }],
    });

    expect(resumen).not.toContain('<script>alert(1)</script>');
    expect(resumen).toContain('&lt;script&gt;alert(1)&lt;/script&gt;');
    expect(resumen).toContain('&lt;b&gt;X&lt;/b&gt;');
    expect(invoice).toContain('USD 12.50');
  });

  it('no arrastra mensajes de marca antiguos ni mojibake en los documentos generados', () => {
    const cotizacion = pdfDocs.generarCotizacion({ items: [], totales: {} });
    const packing = pdfDocs.generarPackingList({ items: [] });
    const invoice = pdfDocs.generarInvoice({ items: [] });
    const resumen = pdfDocs.generarResumenPermisos({ permisos: [] });
    const source = require('fs').readFileSync(require('path').join(__dirname, '..', '..', 'server', 'pdf-docs.js'), 'utf8');

    for (const html of [cotizacion, packing, invoice, resumen]) {
      expect(html).not.toContain('v2.0');
      expect(html).not.toMatch(/[ÃƒÆ’Ã†â€™ÃƒÂ°ÃƒÂ¢]/);
    }

    expect(cotizacion).toContain('COTIZACION DE IMPORTACION');
    expect(cotizacion).toContain('ImportAIAgent Cotizador - valores sujetos a verificacion operativa y aduanera.');
    expect(packing).toContain('Packing list generado por ImportAIAgent Cotizador.');
    expect(invoice).toContain('Generated by ImportAIAgent Cotizador - reference commercial document.');
    expect(resumen).toContain('Resumen generado por ImportAIAgent Cotizador.');
    expect(source).toContain('Genera HTML preparado para imprimir o convertir a PDF.');
    expect(source).not.toContain('Genera HTML listo para imprimir o convertir a PDF.');
    expect(cotizacion).not.toContain('Cotizador de Importacion Peru');
    expect(resumen).toContain('SIN RESTRICCIONES DETECTADAS');
  });
});
